#!/usr/bin/env bash
# Overlays (.dts and .dtbo) from dt/'s .dtsi files into $OUT_DIR/overlays/. Fails unless
# Armbian's DTS plus the overlays equals our DTB, node order included. Each stock.dtb
# given gets the overlays applied and its diff against ours kept.
#
#   tools/overlays.sh [src] [stock.dtb ...]   # src defaults to work/kernel
set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
src=${1:-$here/work/kernel}
shift || true
out=${OUT_DIR:-$here/out}/overlays
patchdirs=("$here"/userpatches/kernel/archive/rockchip64-*)
[[ ${#patchdirs[@]} -eq 1 ]] || { echo "overlays.sh: expected one rockchip64-* patch dir" >&2; exit 1; }
dt=${patchdirs[0]}/dt
board=rk3588s-orangepi-5-pro
normalize=$here/tools/dt-normalize.py
order=$here/tools/dt-order.py

[[ -d $src/arch/arm64/boot/dts/rockchip ]] || { echo "overlays.sh: no kernel tree in $src" >&2; exit 1; }
rm -rf "$out"
mkdir -p "$out"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# dtb <in.dts> <out.dtb> [dtc flags]: cpp as the kernel runs it, then dtc.
dtb() {
	local in=$1 o=$2
	shift 2
	cpp -nostdinc -undef -D__DTS__ -x assembler-with-cpp \
		-I "$src/include" -I "$src/arch/arm64/boot/dts" -I "$src/arch/arm64/boot/dts/rockchip" \
		-I "$dt" "$in" -o "$tmp/pre.dts"
	dtc -q -I dts -O dtb "$@" -o "$o" "$tmp/pre.dts"
}

# Each .dtsi with / as &{/}. Blocks are reordered, as fragments apply in file order:
# &label on Armbian's labels, then /, then &label on the .dtsi's own (dtc merges those into
# / only after it). Otherwise &vdec0_mmu's disabled would beat &rkvdec0_mmu's okay on the
# same node. Nodes are then reversed, as applying reverses them.
overlays=()
for f in "$dt/$board"-*.dtsi; do
	name=${f##*/}
	name=${name%.dtsi}
	{
		echo "// SPDX-License-Identifier: GPL-2.0-only"
		echo "// Generated by tools/overlays.sh from userpatches/.../dt/${f##*/}."
		echo "/dts-v1/;"
		echo "/plugin/;"
		echo
		echo "#include <dt-bindings/clock/rockchip,rk3588-cru.h>"
		echo "#include <dt-bindings/interrupt-controller/arm-gic.h>"
		echo "#include <dt-bindings/interrupt-controller/irq.h>"
		echo "#include <dt-bindings/power/rk3588-power.h>"
		echo "#include <dt-bindings/reset/rockchip,rk3588-cru.h>"
		echo
		# Pass 1: the file's labels, and the paths of nodes under /. Pass 2: sort the blocks,
		# and write `x = &label;` as the path (in an overlay it would be the fragment's).
		awk '
			NR == FNR {
				if (match($0, /^[ \t]*[A-Za-z_][A-Za-z0-9_]*:/)) {
					l = substr($0, RSTART, RLENGTH - 1)
					gsub(/[ \t]/, "", l)
					own[l] = 1
					if (inroot && rdepth == 1) {
						node = substr($0, RSTART + RLENGTH)
						sub(/^[ \t]*/, "", node)
						sub(/[ \t]*\{.*/, "", node)
						path[l] = "/" node
					}
				}
				if (!inroot && /^\/ \{/) inroot = 1
				if (inroot) {
					rdepth += gsub(/\{/, "{") - gsub(/\}/, "}")
					if (rdepth == 0) inroot = 0
				}
				next
			}
			block == "root" && match($0, /= &[A-Za-z_][A-Za-z0-9_]*;/) {
				l = substr($0, RSTART + 3, RLENGTH - 4)
				if (!(l in path)) {
					print "overlays.sh: " FILENAME ": no node under / for the path reference &" l > "/dev/stderr"
					exit 1
				}
				$0 = substr($0, 1, RSTART - 1) "= \"" path[l] "\";" substr($0, RSTART + RLENGTH)
			}
			!block && /^\/ \{/ { block = "root"; sub(/^\/ \{/, "\\&{/} {") }
			!block && /^&[A-Za-z_]/ {
				l = substr($0, 2)
				sub(/[^A-Za-z0-9_].*/, "", l)
				block = (l in own) ? "late" : "early"
			}
			block {
				text[block] = text[block] pending $0 "\n"
				pending = ""
				depth += gsub(/\{/, "{") - gsub(/\}/, "}")
				if (depth == 0) block = ""
				next
			}
			{ pending = pending $0 "\n" }
			END { printf "%s%s\n%s\n%s", text["head"] pending, text["early"], text["root"], text["late"] }
		' "$f" "$f"
	} | python3 "$order" reverse > "$out/$name.dts"
	dtb "$out/$name.dts" "$out/$name.dtbo" -@
	overlays+=("$out/$name.dtbo")
done
[[ ${#overlays[@]} -gt 0 ]] || { echo "overlays.sh: no $board-*.dtsi in $dt" >&2; exit 1; }

# Armbian's DTS: ours without our includes.
grep -v "^#include \"$board-.*\.dtsi\"" "$dt/$board.dts" > "$tmp/base.dts"
dtb "$tmp/base.dts" "$tmp/base.dtb" -@
dtb "$dt/$board.dts" "$tmp/ours.dtb" -@
fdtoverlay -i "$tmp/base.dtb" -o "$tmp/merged.dtb" "${overlays[@]}"

norm() { dtc -q -I dtb -O dts -s "$1" | python3 "$normalize"; }
norm "$tmp/ours.dtb" > "$tmp/ours.norm"
if ! diff -u --label ours --label overlays "$tmp/ours.norm" <(norm "$tmp/merged.dtb") > "$out/check.diff"; then
	cat "$out/check.diff" >&2
	echo "overlays.sh: Armbian's DTS with the overlays differs from ours ($out/check.diff)" >&2
	exit 1
fi
rm "$out/check.diff"
# The sorted compare can't see node order.
for o in "${overlays[@]}"; do
	fdtoverlay -i "$tmp/base.dtb" -o "$tmp/one.dtb" "$o"
	python3 "$order" check "$tmp/base.dtb" "$tmp/ours.dtb" "$tmp/one.dtb" ||
		{ echo "overlays.sh: Armbian's DTS with ${o##*/} has nodes in another order than ours" >&2; exit 1; }
done
echo "overlays: $(cd "$out" && echo *.dts) match $board.dtb on Armbian's DTS from $src, in the same node order"

for stock in "$@"; do
	name=${stock##*/}
	fdtoverlay -i "$stock" -o "$tmp/stock.dtb" "${overlays[@]}"
	if diff -u --label ours --label "$name+overlays" "$tmp/ours.norm" <(norm "$tmp/stock.dtb") > "$out/$name.diff"; then
		echo "$stock: applies, and matches ours"
	else
		echo "$stock: applies; $(grep -c '^[-+][^-+]' "$out/$name.diff") lines differ from ours ($out/$name.diff)"
	fi
done

if [[ $EUID -eq 0 ]]; then
	chown -R --reference="$here" "$out"
fi
